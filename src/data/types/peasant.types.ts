/**
 * Peasant System Types
 * Player-wide peasant population and allocation
 */

import type { PlayerId, EntityId, Coordinates } from './game.types';

/**
 * Peasant allocation target type
 */
export enum AllocationTargetType {
  BUILDING = 'BUILDING',
  RESOURCE_DEPOSIT = 'RESOURCE_DEPOSIT',
}

/**
 * Peasant allocation to a building or resource
 */
export interface PeasantAllocation {
  targetType: AllocationTargetType;
  targetId: EntityId; // Building entity ID or resource deposit ID
  coordinates: Coordinates;
  peasantCount: number;
  requiredForOptimal: number; // For 100% efficiency
  currentEfficiency: number; // 0.0 to 5.0 (0% to 500%)
}

/**
 * Player peasant state
 */
export interface PlayerPeasantState {
  playerId: PlayerId;

  // Population
  totalPeasants: number; // Generated by infrastructure buildings
  allocatedPeasants: number;
  unallocatedPeasants: number;

  // Allocations
  allocations: Map<EntityId, PeasantAllocation>;

  // Sources
  peasantSources: PeasantSource[]; // Buildings generating peasants
}

/**
 * Source of peasant population
 */
export interface PeasantSource {
  buildingEntityId: EntityId;
  buildingId: string;
  coordinates: Coordinates;
  peasantsGenerated: number;
}

/**
 * Peasant allocation change
 */
export interface PeasantAllocationChange {
  playerId: PlayerId;
  targetId: EntityId;
  previousCount: number;
  newCount: number;
  efficiencyChange: {
    before: number;
    after: number;
  };
}

/**
 * Peasant production calculation
 */
export interface PeasantProductionCalculation {
  allocatedPeasants: number;
  requiredPeasants: number;
  efficiencyMultiplier: number; // 0.0 to 5.0
  baseProduction: number;
  actualProduction: number;
}

/**
 * Peasant allocation validation
 */
export interface PeasantAllocationValidation {
  valid: boolean;
  error?: string;
  availablePeasants: number;
  requestedAllocation: number;
  wouldExceedAvailable: boolean;
}

/**
 * Player peasant statistics
 */
export interface PlayerPeasantStats {
  playerId: PlayerId;
  totalPeasants: number;
  allocated: number;
  unallocated: number;
  utilizationRate: number; // Percentage allocated
  averageEfficiency: number; // Average across all allocations
  suboptimalAllocations: number; // Count of allocations below 100%
}
